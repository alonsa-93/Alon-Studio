const STORE_KEY = 'alon.lang';

function initial(): Lang {
  try {
    const v = localStorage.getItem(STORE_KEY);
    if (v === 'en' || v === 'he') return v;
  } catch {
    /* storage blocked: Hebrew */
  }
  return 'he';
}

let current: Lang = initial();

function applyToDocument(lang: Lang) {
  if (typeof document === 'undefined') return; // the key check runs this file in Node
  const html = document.documentElement;
  html.lang = lang;
  html.dir = lang === 'he' ? 'rtl' : 'ltr';
}
applyToDocument(current);

/** React components subscribe to this so a language switch re-renders the studio. */
export const useLang = create<{ lang: Lang }>(() => ({ lang: current }));

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang) {
  if (lang === current) return;
  current = lang;
  try {
    localStorage.setItem(STORE_KEY, lang);
  } catch {
    /* not kept for next time */
  }
  applyToDocument(lang);
  useLang.setState({ lang });
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const entry: Entry | undefined = (STRINGS as Record<string, Entry>)[key];
  let s = entry ? entry[current === 'en' ? 1 : 0] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** A label for a value from a shared list (transitions, looks, styles...): English from the
 *  strings file when there is one, otherwise the Hebrew label the list carries. */
export function tl(group: string, id: string, he: string): string {
  if (current === 'he') return he;
  const entry = (STRINGS as Record<string, Entry>)[`${group}.${id}`];
  return entry ? entry[1] : he;
}

/** Number formatting for the current language (decimal point, grouping). */
export function num(n: number, digits = 0): string {
  return n.toLocaleString(current === 'he' ? 'he-IL' : 'en-US', { maximumFractionDigits: digits, minimumFractionDigits: digits });
}
